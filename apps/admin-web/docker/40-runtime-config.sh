#!/bin/sh
set -eu

: "${CURRALZAP_API_BASE_URL:=http://localhost:8080}"
: "${CURRALZAP_GOOGLE_CLIENT_ID:=}"
: "${CURRALZAP_FACEBOOK_APP_ID:=}"
: "${CURRALZAP_MICROSOFT_CLIENT_ID:=}"
export CURRALZAP_API_BASE_URL CURRALZAP_GOOGLE_CLIENT_ID CURRALZAP_FACEBOOK_APP_ID CURRALZAP_MICROSOFT_CLIENT_ID

envsubst '$CURRALZAP_API_BASE_URL $CURRALZAP_GOOGLE_CLIENT_ID $CURRALZAP_FACEBOOK_APP_ID $CURRALZAP_MICROSOFT_CLIENT_ID' \
  < /opt/curralzap/runtime-config.js.template \
  > /usr/share/nginx/html/config.js
